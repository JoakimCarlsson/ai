package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const fixture = `package demo

import (
	"github.com/joakimcarlsson/ai/llm"
)

const (
	GPT41 string = "demo.gpt-4.1"
)

var Models = map[string]llm.Model{
	GPT41: {
		ID:               GPT41,
		Name:             "Demo – GPT 4.1",
		Provider:         "demo",
		APIModel:         "openai/gpt-4.1",
		CostPer1MIn:      2,
		ContextWindow:    1047576,
		DefaultMaxTokens: 20000,
	},
}
`

func writeFixture(t *testing.T) string {
	t.Helper()

	path := filepath.Join(t.TempDir(), "models.go")
	if err := os.WriteFile(path, []byte(fixture), 0o600); err != nil {
		t.Fatalf("writing fixture: %v", err)
	}
	return path
}

func demoTarget() target {
	return target{
		kind:       kindChat,
		path:       "demo/models.go",
		pkg:        "demo",
		importPath: "github.com/joakimcarlsson/ai/llm",
		typeExpr:   "llm.Model",
		source:     "https://example.test/models",
		idPrefix:   "demo.",
		order:      chatFields,
		defaults:   map[string]string{"Provider": `"demo"`},
	}
}

func TestReadCatalogKeysByAPIModel(t *testing.T) {
	cat, err := readCatalog(writeFixture(t))
	if err != nil {
		t.Fatalf("readCatalog: %v", err)
	}

	e, ok := cat.entries["openai/gpt-4.1"]
	if !ok {
		t.Fatalf("entry not found, got %v", cat.entries)
	}
	if e.constName != "GPT41" {
		t.Errorf("constName = %q, want GPT41", e.constName)
	}
	if e.constVal != "demo.gpt-4.1" {
		t.Errorf("constVal = %q, want demo.gpt-4.1", e.constVal)
	}
	if got := e.fields["ContextWindow"]; got != "1047576" {
		t.Errorf("ContextWindow = %q, want 1047576", got)
	}
}

